namespace UpscaleSDK.Core.Input.Core.Enums
{
    /// <summary>
    /// Defines how a button input is triggered.
    /// </summary>
    public enum ButtonTrigger
    {
        /// <summary>
        /// Triggered while the button is held down.
        /// </summary>
        Hold,

        /// <summary>
        /// Triggered when the button is pressed.
        /// </summary>
        Press,

        /// <summary>
        /// Triggered when the button is released.
        /// </summary>
        Release
    }
}